// By hand, if Riot renames a starter icon: `pnpm --filter ni-han-bao-bot icons`.
// Writes bot/src/starter-icons.ts: the English names of starter icons 0 to 28, which the
// client's icon picker searches by. Data Dragon has no icon names, CommunityDragon does.
import { writeFileSync } from "node:fs";

const SOURCE = "https://raw.communitydragon.org/latest/plugins/rcp-be-lol-game-data/global/default/v1/summoner-icons.json";

const icons = (await (await fetch(SOURCE)).json()) as { id: number; title: string }[];
const names = Array.from({ length: 29 }, (_, id) => {
  const title = icons.find((icon) => icon.id === id)?.title;
  if (!title) throw new Error(`${SOURCE} has no title for icon ${id}`);
  return title;
});
writeFileSync(
  new URL("starter-icons.ts", import.meta.url),
  `// Generated by src/icons.ts from ${SOURCE} on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n` +
    `/** English names of starter icons 0 to 28, by id. */\n` +
    `export const STARTER_ICON_NAMES: readonly string[] = ${JSON.stringify(names, null, 2)};\n`,
);
