import { cardImageUrl } from "@/bot/src/card-match";
import { discordMarkdown, type Token } from "@/lib/discord-markdown";
import replies from "@/lib/replies.json";
import { cn } from "@/lib/utils";
import { CornerDownRight, ExternalLink, Eye, ImageIcon } from "lucide-react";
import { Fragment } from "react";

interface Embed {
  title?: string;
  url?: string;
  description?: string;
  color?: number;
  fields?: { name: string; value: string; inline?: boolean }[];
  image?: { url: string };
  footer?: { text: string };
}
/** One of Discord's message components (its API shape): `type` says which, see ComponentView. */
interface Component {
  type?: number;
  components?: Component[];
  accessory?: Component;
  content?: string;
  media?: { url: string };
  description?: string;
  items?: { media: { url: string }; description?: string }[];
  divider?: boolean;
  accent_color?: number;
  label?: string;
  style?: number;
}
/** A message as the bot sends it (Discord's API shape), plus how it was asked for. */
export interface Reply {
  command: string | null;
  ephemeral: boolean;
  channels: Record<string, string>;
  users: Record<string, string>;
  /** The official icon each of the bot's emojis (<:rb_fury:id>) shows. */
  emojis: Record<string, string>;
  message: { content?: string; embeds?: Embed[]; components?: Component[]; flags?: number };
}
/** What drawing a reply's text needs. */
interface Names {
  channels: Record<string, string>;
  users: Record<string, string>;
  emojis: Record<string, string>;
}

// Generated by the bot's reply builders (bot/src/reply-examples.ts), never edited by hand.
const REPLIES: Record<keyof typeof replies, Reply> = replies;

// Discord's button styles: 1 primary, 2 secondary, 3 success, 4 danger, 5 link.
const BUTTON = [
  "bg-secondary",
  "bg-primary text-primary-foreground",
  "bg-secondary",
  "bg-success text-background",
  "bg-destructive text-destructive-foreground",
  "bg-secondary",
];
const rgb = (color: number) => `rgb(${color >> 16} ${(color >> 8) & 255} ${color & 255})`;

function Markdown({ text, channels, users, emojis }: { text: string } & Names) {
  const draw = (tokens: Token[]) =>
    tokens.map((t, i) =>
      t.kind === "bold" ? (
        <strong key={i}>{draw(t.children)}</strong>
      ) : t.kind === "channel" ? (
        <span key={i} className="rounded bg-gold/10 px-0.5 text-gold">
          #{t.name}
        </span>
      ) : t.kind === "user" ? (
        <span key={i} className="rounded bg-gold/10 px-0.5 text-gold">
          @{t.name}
        </span>
      ) : t.kind === "link" ? (
        <span key={i} className="text-gold">
          {t.url}
        </span>
      ) : t.kind === "emoji" ? (
        emojis[t.name] ? (
          // The bot's emoji is a copy of Riot's icon: the docs show the original on Riot's CDN.
          // eslint-disable-next-line @next/next/no-img-element
          <img key={i} src={cardImageUrl(emojis[t.name], 64)} alt={`:${t.name}:`} className="inline-block size-[1.375em] object-contain align-[-0.3em]" />
        ) : (
          `:${t.name}:`
        )
      ) : (
        t.text
      ),
    );
  const lines = text.split("\n");
  return (
    <div className="whitespace-pre-line break-words">
      {lines.map((line, i) => {
        // Discord's headings (### ) and subtext (-# ), which only its newer components draw.
        const heading = /^#{1,3} (.*)$/.exec(line);
        const subtext = /^-# (.*)$/.exec(line);
        return heading ? (
          <p key={i} className="text-base font-bold">
            {draw(discordMarkdown(heading[1], channels, users))}
          </p>
        ) : subtext ? (
          <p key={i} className="text-xs text-muted-foreground">
            {draw(discordMarkdown(subtext[1], channels, users))}
          </p>
        ) : (
          <Fragment key={i}>
            {draw(discordMarkdown(line, channels, users))}
            {i < lines.length - 1 && "\n"}
          </Fragment>
        );
      })}
    </div>
  );
}

function EmbedView({ embed, channels, users, emojis }: { embed: Embed } & Names) {
  const color = embed.color === undefined ? undefined : rgb(embed.color);
  const image = embed.image?.url;
  return (
    <div className="flex max-w-lg flex-col gap-2 rounded-md border-l-4 border-l-muted-foreground bg-secondary p-3" style={{ borderLeftColor: color }}>
      {embed.title && <p className={cn("font-semibold", embed.url && "text-gold")}>{embed.title}</p>}
      {embed.description && <Markdown text={embed.description} channels={channels} users={users} emojis={emojis} />}
      {embed.fields && (
        <dl className="grid grid-cols-1 gap-2 sm:grid-cols-3">
          {embed.fields.map((f) => (
            <div key={f.name} className={cn(!f.inline && "sm:col-span-3")}>
              <dt className="font-semibold">{f.name}</dt>
              <dd>
                <Markdown text={f.value} channels={channels} users={users} emojis={emojis} />
              </dd>
            </div>
          ))}
        </dl>
      )}
      {image?.startsWith("attachment://") ? (
        // The bot uploads this image with the message; the docs have no copy of it.
        <div className="flex aspect-[1200/630] flex-col items-center justify-center gap-1 rounded-md border border-dashed text-xs text-muted-foreground">
          <ImageIcon aria-hidden className="size-6" />
          {image.slice("attachment://".length)}
        </div>
      ) : (
        // eslint-disable-next-line @next/next/no-img-element
        image && <img src={image} alt={embed.title ?? ""} loading="lazy" className="max-h-80 self-start rounded-md" />
      )}
      {embed.footer && <p className="text-xs text-muted-foreground">{embed.footer.text}</p>}
    </div>
  );
}

/** Discord's components: 17 container, 9 section, 10 text, 11 thumbnail, 12 gallery, 14 separator, 1 row of 2 buttons. */
function ComponentView({ c, names }: { c: Component; names: Names }) {
  const children = c.components?.map((child, i) => <ComponentView key={i} c={child} names={names} />);
  switch (c.type) {
    case 17:
      return (
        <div
          className="flex max-w-lg flex-col gap-2 rounded-md border-l-4 border-l-muted-foreground bg-secondary p-3"
          style={{ borderLeftColor: c.accent_color === undefined ? undefined : rgb(c.accent_color) }}
        >
          {children}
        </div>
      );
    case 9:
      return (
        <div className="flex gap-3">
          <div className="flex min-w-0 flex-1 flex-col gap-2">{children}</div>
          {c.accessory && <ComponentView c={c.accessory} names={names} />}
        </div>
      );
    case 10:
      return <Markdown text={c.content ?? ""} {...names} />;
    case 11:
      // eslint-disable-next-line @next/next/no-img-element
      return <img src={c.media?.url} alt={c.description ?? ""} loading="lazy" className="max-h-20 max-w-20 shrink-0 self-start rounded-md object-contain" />;
    case 12:
      return (
        <div className="flex flex-wrap gap-1">
          {c.items?.map((item) => (
            // eslint-disable-next-line @next/next/no-img-element
            // Several images share the row, as Discord tiles them.
            <img
              key={item.media.url}
              src={item.media.url}
              alt={item.description ?? ""}
              loading="lazy"
              className={cn("rounded-md", (c.items?.length ?? 0) > 1 ? "max-h-32" : "max-h-80")}
            />
          ))}
        </div>
      );
    case 14:
      return c.divider === false ? <div aria-hidden className="h-1" /> : <hr className="border-border" />;
    case 2:
      return (
        <span className={cn("inline-flex items-center gap-1.5 rounded-md px-4 py-1.5 font-medium", BUTTON[c.style ?? 2])}>
          {c.label}
          {c.style === 5 && <ExternalLink aria-hidden className="size-3.5" />}
        </span>
      );
    default:
      // A row of buttons; the older replies leave its type out.
      return <div className="flex flex-wrap gap-2">{children}</div>;
  }
}

/** A Discord-style drawing of a bot message: not a screenshot, the bot's own reply data. */
export function DiscordMessage({ command, ephemeral, channels, users, emojis, message }: Reply) {
  const names = { channels, users, emojis };
  return (
    // Always Discord's dark look, whatever the site's theme.
    <div className="dark flex flex-col gap-1 rounded-xl border bg-card p-4 text-sm text-foreground">
      {command && (
        <p className="flex items-center gap-1 pl-5 text-xs text-muted-foreground">
          <CornerDownRight aria-hidden className="size-3" />
          You used <span className="font-medium text-gold">{command}</span>
        </p>
      )}
      <div className="flex gap-3">
        <div aria-hidden className="flex size-10 shrink-0 items-center justify-center rounded-full bg-primary font-semibold text-primary-foreground">
          n
        </div>
        <div className="flex min-w-0 flex-1 flex-col gap-2">
          <p className="flex items-center gap-2">
            <span className="font-semibold">nexus</span>
            <span className="rounded bg-primary px-1 text-xs font-semibold text-primary-foreground">APP</span>
          </p>
          {message.content && <Markdown text={message.content} {...names} />}
          {message.embeds?.map((e, i) => <EmbedView key={i} embed={e} {...names} />)}
          {message.components?.map((c, i) => <ComponentView key={i} c={c} names={names} />)}
          {ephemeral && (
            <p className="flex items-center gap-1 text-xs text-muted-foreground">
              <Eye aria-hidden className="size-3" />
              Only you can see this
            </p>
          )}
        </div>
      </div>
    </div>
  );
}

/** One of the bot's replies (lib/replies.json), drawn, with a caption saying so. */
export function ReplyExample({ name }: { name: keyof typeof replies }) {
  return (
    <figure className="flex flex-col gap-2">
      <DiscordMessage {...REPLIES[name]} />
      <figcaption className="text-xs text-muted-foreground">Example reply, drawn from the bot&apos;s code</figcaption>
    </figure>
  );
}
